"""
3创建索引.py —— 向量索引核心笔记（简洁完整）

════════════════════════════════════════════════════════════
0. 一张表里有什么
════════════════════════════════════════════════════════════
集合 ≈ 一张表。一行大致是：

  id | 原文（张三那段话） | embedding 列（一串 float）

- 「向量字段」= 表上的一列（列名你定，如 embedding）
- 列里的数 = embedding 模型算出来，你 insert 进去
- 多向量列 = 同一行多份向量（标题一份、正文一份）；搜时选「哪一列」

小例子一行：
  原文: 「我是工程师，叫张三，21岁」
  embedding: [0.12, -0.05, ...]   ← 真实数据


════════════════════════════════════════════════════════════
1. 索引是什么（真实存在）
════════════════════════════════════════════════════════════
索引 ≠ 原文，≠ 再存一遍张三。
索引 = 额外存的「加速目录」，占磁盘/内存。

类比：正文是书，索引是目录。删目录书还在，只是翻得慢。

IVF 目录长什么样：
  · 若干桶中心（每个中心也是一个向量）
  · 每条真实向量归到一个桶：桶37 → [张三id, …]


════════════════════════════════════════════════════════════
2. 桶中心怎么来的（学名）
════════════════════════════════════════════════════════════
学名：k-means 聚类；挂到检索上叫 IVF / IVFFlat（倒排+桶内精比）。
统称：ANN 近似最近邻（用一点精度换速度）。

nlist=128 → 聚成 128 类。
做法（建索引时算一次，不是每次搜索重算）：
  反复「每条向量归最近中心 → 桶内向量取平均更新中心」
  → 桶中心 ≈ 这一拨相似向量的「平均位置」

张三进哪桶：看他的向量离哪个中心近（建索引时定好）。


════════════════════════════════════════════════════════════
3. 搜索时索引怎么起作用
════════════════════════════════════════════════════════════
问题也变成向量 q。例如问：「谁是21岁工程师？」

无索引：q 和表里每一条向量比距离 → 慢但不易漏。

有 IVF 后：
  ① q 和全部 128 个桶中心比（很便宜）
  ② 按距离排序，取最近的 nprobe 个中心（如 16）——不是事先知道「去桶37」
     桶37被选中，只因它的中心离 q 近
  ③ 只在这 16 个桶里的真实向量上精比 → 取出 top-k
  ④ 用 id 拿回原文「我叫张三…」

因为相似内容常在同一/邻近桶，多数时候能搜到；
若最优解在没探到的桶里 → 这次就是漏了（nprobe 不会自动再扩）。


════════════════════════════════════════════════════════════
4. 两套参数（别混）
════════════════════════════════════════════════════════════
建索引 create_index（本文件）     搜索 search 的 param
-------------------------------   --------------------------
metric: L2  怎么量远近            必须同一套 L2
IVF_FLAT    用分桶加速            走这套目录
nlist=128   一共多少桶（固定）     —
—                                 nprobe=16  本次探几个桶

一句话：create = 印好 128 本分册目录；search = 只翻其中 nprobe 本。


════════════════════════════════════════════════════════════
5. 召回 / 召回率
════════════════════════════════════════════════════════════
召回：该找到的有没有找回来。
召回率 = 找对的 / 本来该找到的。  例：5 条相关命中 4 条 → 80%。

nprobe 大 → 召回更好、更慢；nprobe 小 → 更快、更容易漏。


════════════════════════════════════════════════════════════
6. 索引何时生效；load 是什么
════════════════════════════════════════════════════════════
· 一个向量字段上通常同时只有一套索引；搜字段 → 自动用该字段索引
  （不是搜索时从「索引菜单」勾选多套）
· create_index：把目录算好存盘
· load()：常无参；把本集合的数据+已建索引装到可搜状态（不是选索引）
· search：真正查；传字段名 + nprobe 等

典型顺序：插入数据 → create_index → load → search


════════════════════════════════════════════════════════════
7. 和 all.py（Chroma）的关系
════════════════════════════════════════════════════════════
同一件事：按向量找近邻。
Milvus：create_index / load / search 写在明处（本文件）。
all.py：collection.query(...) 一句完成检索；索引多半自动维护，无 load。

小数据可以不建索引也能查；索引价值在数据量大时少算距离。
"""

from pymilvus import Collection, connections
from utils.main import printLine

connections.connect("default", host="localhost", port="19530", db_name="rensheng")
collection = Collection("example")

# 创建索引：对字段 embedding 做 k-means 分桶，目录落盘（只准备，不搜索）
index_params = {
    "metric_type": "L2",
    "index_type": "IVF_FLAT",
    "params": {"nlist": 128},  # 128 个桶中心
}
collection.create_index("embedding", index_params)
printLine("索引创建成功")

# 搜索前装载集合（数据+索引）；无参 = 整集合就绪，不是挑选哪个索引
collection.load()


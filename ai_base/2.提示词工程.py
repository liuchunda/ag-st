# 常用技巧

# 零样本提示（Zero-Shot）
# 适合：翻译、摘要、简单分类、解释概念等常见任务。
# 示例：「把下面句子翻译成英文，只输出译文：今天天气很好。」

# 少样本提示（Few-Shot）
# 少样本：在任务说明前先给 1～3 个「输入 → 输出」示例，让模型模仿格式。
# 适合：零样本效果不稳定时，如特定风格分类、固定格式抽取。
# 示例不宜过多，否则占用上下文、增加费用。
# 在 API 里通常把示例写进同一条 user 消息，或拆成多轮 user/assistant 历史。


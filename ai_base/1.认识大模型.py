#  人工智能（AI） 是让机器模拟人类智能的技术，包括学习、推理、判断等能力。
# AI 的缩写是Artificial Intelligence，中文意思是「人工智能」。
#  NLP(natural language processing)自然语言处理.是专门研究计算机和人类语言之间交互的一门学科.
# 机器学习 让程序从样本数据中自动找规律，而不是人写死每一条规则。
# 深度学习：机器学习的一个分支，用多层「神经网络」处理复杂数据（文字、图片、声音）。
# 大模型(large language model) 属于深度学习，专门处理自然语言的模型.

# 什么是 Token
# 模型上下文的大小，包含系统提示词，历史对话，用户输入，模型输出，工具rag，检索到的文档，工具的返回结果等。都包含在内
# Token 是大模型处理文本的最小单位，可以是一个字、一个词，或词的一部分。
# 英文里 1 个 token 大约对应 3～4 个字符；中文里 1 个汉字往往接近 1 个 token。
# 模型有上下文窗口限制，例如「8K」「128K」表示一次最多能处理多少 token。
# 对话越长、输入越多，消耗的 token 越多，调用费用通常也越高（按量计费时）。

# 大语言模型

# Billion 十亿
# 0或者1表示一个比特bit，8个比特组成一个字节byte
# GB是吉字节的缩写，吉字节的英文是giga byte，缩写为GB。
# 字节byte 1B = 8bit  这里的B是bite的缩写
# 千字节kilobyte 1KB = 1024B
# 兆megabyte 1MB = 1024KB
# 吉gigabyte 1GB = 1024MB
# 太terabyte 1TB = 1024GB
# LLM = Large Language Model，中文常称「大语言模型」或简称「大模型」。
# TB是万亿的缩写，万亿的英文是trillion，缩写为T。B是字节的缩写，字节的英文是byte，缩写为B。
# GB是1024MB，MB是兆字节的缩写，兆字节的英文是megabyte，缩写为MB。

# AGI 是Artificial General Intelligence的缩写，中文意思是「通用人工智能」。

# AIGC（Artificial Intelligence Generated Content）：指利用 AI 自动生成文本、图像、音频、视频等内容，是当下大模型的主要应用形态。
# Generated 是生成的意思，Content 是内容的意思。


# 开源模型：公开模型权重，可下载到本地或用云 API 调用（如 DeepSeek、Qwen 开源版）。
# 闭源模型：不公开权重，只能通过官网或 API 使用（如 GPT-4o），效果往往更好。

# 大模型参数例如70B，表示模型有700亿个参数。1个参数大概占用2个字节，所以70B的模型大概占用1.4TB的内存。


# 幻觉：模型可能自信地编造不存在的事实，重要信息要人工核实。
# 隐私：不要把密码、身份证号等敏感数据发给第三方 API。
# 成本：高频调用会产生费用，注意设置用量上限。
# 合规：生成内容需符合法律法规和平台使用协议。

